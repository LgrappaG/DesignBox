export function compileVisualForgeBlueprintHTML(
  config: VisualForgeConfig,
  customProps: CustomPropDefinition[] = []
): string {
  const dirStyle =
    config.layout === 'row'
      ? 'display:flex;align-items:center;gap:12px;'
      : config.layout === 'grid2'
      ? 'display:grid;grid-template-columns:1fr 1fr;gap:10px;align-items:center;'
      : 'display:flex;flex-direction:column;justify-content:center;gap:8px;';

  const glassStyle = config.glassmorphism
    ? 'background:rgba(255,255,255,0.08);backdrop-filter:blur(8px);'
    : '';
  const glowStyle = config.glowBorder ? 'box-shadow:0 0 14px {{accent}};' : '';

  const avatarPart = config.showAvatarSlot
    ? `<img src="{{image}}" alt="{{title}}" style="width:58px;height:58px;object-fit:cover;border-radius:8px;border:2px solid {{accent}};flex-shrink:0;" />`
    : '';

  const badgePart = config.showBadgeSlot
    ? `<span style="padding:2px 8px;border-radius:999px;background:{{accent}};color:#fff;font-size:10px;font-weight:700;">{{badge}}</span>`
    : '';

  const headerPart = config.showHeaderSlot
    ? `<div style="display:flex;align-items:center;justify-content:space-between;gap:6px;">
        <span style="font-weight:700;font-size:13px;color:{{accent}};">{{title}}</span>
        ${badgePart}
      </div>`
    : badgePart;

  const bodyPart = config.showBodySlot
    ? `<div style="font-size:11px;opacity:0.88;line-height:1.4;white-space:pre-line;">{{subtitle}}</div>`
    : '';

  const progressPart = config.showProgressSlot
    ? `<div style="width:100%;margin-top:4px;">
        <div style="display:flex;justify-content:space-between;font-size:10px;font-weight:700;margin-bottom:3px;">
          <span>{{stat_label}}</span>
          <span>{{stat_value}}%</span>
        </div>
        <div style="width:100%;height:6px;background:rgba(150,150,150,0.25);border-radius:999px;overflow:hidden;">
          <div style="width:{{stat_value}}%;height:100%;background:{{accent}};border-radius:999px;"></div>
        </div>
      </div>`
    : '';

  const extraPropsPart =
    customProps.length > 0
      ? `<div style="display:flex;flex-wrap:wrap;gap:6px;margin-top:4px;">
          ${customProps
            .filter((p) => !['badge', 'stat_label', 'stat_value', 'button_text'].includes(p.key))
            .map(
              (p) =>
                `<span style="font-size:10px;padding:2px 6px;border-radius:4px;background:rgba(0,0,0,0.15);border:1px solid {{accent}};"><strong>${p.label}:</strong> {{${p.key}}}</span>`
            )
            .join('')}
        </div>`
      : '';

  const buttonPart = config.showButtonSlot
    ? `<a href="{{link}}" target="_blank" style="margin-top:4px;padding:5px 12px;border-radius:6px;background:{{accent}};color:#fff;text-decoration:none;font-size:11px;font-weight:700;text-align:center;display:inline-block;">{{button_text}} ↗</a>`
    : '';

  return `<div style="height:100%;padding:4px;${dirStyle}${glassStyle}${glowStyle}">
  ${avatarPart}
  <div style="flex:1;min-width:0;display:flex;flex-direction:column;gap:4px;text-align:left;">
    ${headerPart}
    ${bodyPart}
    ${progressPart}
    ${extraPropsPart}
    ${buttonPart}
  </div>
</div>`;
}

