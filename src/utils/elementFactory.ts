export function buildBlueprintInstanceElement(
  bp: CustomWidgetBlueprint,
  elements: DesignElement[],
  uiTheme: UiTheme
): DesignElement {
  const id = `cw-${Date.now().toString().slice(-4)}`;
  const maxRow = elements.reduce((m, e) => Math.max(m, e.rowIndex), 0);
  const defaultPropsMap: Record<string, string> = {};
  (bp.customPropDefs || []).forEach((p) => {
    defaultPropsMap[p.key] = p.defaultValue;
  });
  const isLight = uiTheme !== 'carbon';

  return {
    id,
    type: 'custom_widget',
    label: bp.name,
    content: bp.defaultContent,
    subContent: bp.defaultSubContent,
    url:
      bp.defaultUrl ||
      'https://images.unsplash.com/photo-1579783902614-a3fb3927b675?w=200&auto=format&fit=crop&q=80',
    customHtml: bp.htmlTemplate,
    customBlueprintId: bp.id,
    customPropDefs: bp.customPropDefs ? [...bp.customPropDefs] : [],
    customProps: defaultPropsMap,
    x: 40 + ((elements.length * 20) % 180),
    y: 40 + ((elements.length * 20) % 140),
    width: bp.defaultWidth,
    height: bp.defaultHeight,
    zIndex: 15 + elements.length,
    opacity: 100,
    order: elements.length,
    rowIndex: maxRow + 1,
    colSpan: 6,
    bgColor: isLight ? '#F2EFE9' : '#242220',
    textColor: isLight ? '#2C2A28' : '#ece7df',
    borderColor: '#C86D51',
    borderWidth: 1,
    borderStyle: 'solid',
    borderRadius: 8,
    padding: 12,
    fontSize: 13,
    fontFamily: 'sans',
    fontWeight: 'medium',
    textAlign: 'left',
    shadow: 'sm',
    hoverEffect: 'lift',
    idleAnimation: 'none',
  };
}

export function buildElementFromAssetPreset(
  preset: AssetPreset,
  elements: DesignElement[],
  uiTheme: UiTheme,
  editingContainer: DesignElement | null
): DesignElement {
  const base = buildDefaultElement(preset.type, elements, uiTheme, editingContainer);
  return {
    ...base,
    id: `ast-${preset.id.replace(/^ast-/, '')}-${Date.now().toString().slice(-3)}`,
    label: preset.name,
    content: preset.content,
    url: preset.url ?? base.url,
    stickerIcon: preset.stickerIcon ?? base.stickerIcon,
    width: preset.defaultWidth,
    height: preset.defaultHeight,
    bgColor: preset.bgColor ?? base.bgColor,
    borderColor: preset.borderColor ?? base.borderColor,
    borderStyle: preset.borderStyle ?? base.borderStyle,
    frameStyle: preset.category === 'stamps' ? 'stamp' : base.frameStyle,
    pinnedOverlay: preset.category === 'stickers' || preset.category === 'washi' || preset.category === 'stamps',
    zIndex: Math.max(base.zIndex || 10, 35 + elements.length),
  };
}

export function buildElementFromFaIcon(
  faClass: string,
  iconLabel: string,
  mode: 'watermark' | 'badge',
  elements: DesignElement[],
  uiTheme: UiTheme,
  editingContainer: DesignElement | null
): DesignElement {
  const base = buildDefaultElement(
    mode === 'watermark' ? 'fa_watermark' : 'badge',
    elements,
    uiTheme,
    editingContainer
  );
  return {
    ...base,
    id: `fa-${Date.now().toString().slice(-4)}`,
    label: mode === 'watermark' ? `FA Icon (${iconLabel})` : `${iconLabel} Badge`,
    faIcon: faClass,
    content: mode === 'watermark' ? faClass : iconLabel.toUpperCase(),
  };
}

